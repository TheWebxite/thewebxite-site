"use client";

import { useEffect, useRef, useState } from "react";
import gsap from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { LAYERS, SERVICES, type LayerKey } from "@/data/services";

/**
 * selected archetype: sticky-column-narrative
 * selected section:   sticky-list-detail
 *
 * The page's ONE pinned section and its only tier-2 moment. The left column
 * (1-5) holds the four-layer ecosystem from p6; the right column (7-12) scrolls
 * the six solutions from p5 natively -- never scrubbed. Column 6 stays
 * genuinely empty: no divider rule. This is the page's deliberate grid break.
 *
 * WHAT THE UNDERLINE MEANS, and why it used to mean nothing. Each solution
 * belongs to one layer, and scrolling it into view marks that layer on the
 * left. That only reads as a progression if the solutions ARRIVE in layer
 * order — and they did not: the deck's p5 order mapped to layers 1, 4, 3, 2,
 * 4, 2, so the mark bounced up and down a list whose heading promises the
 * opposite. The list is now GENERATED by walking the layers and taking each
 * one's solutions, so the mark can only ever travel downward. It descends
 * because of how the array is built, not because someone ordered it by hand
 * and has to remember to keep it that way.
 *
 * The layer is NOT repeated above each solution. It was for one revision,
 * and it read as duplication: the left column already names all four, and
 * with the order fixed the mark walks down them in step with the scroll,
 * which is the relationship stating itself.
 *
 * Active-layer changes are instant, not transitioned: a fading highlight reads
 * as lag.
 *
 * Grain ground: this is one of the argument sections, not the proof, so it
 * carries the same canvas as Hero and Gap. Text colour follows the ground --
 * text/text-muted, never ink/ink-muted, which are for the flat surface.
 */

/* Solutions in LAYER order, derived from the single source in
   data/services.ts rather than a second copy kept in step by hand. The two
   lists had already drifted apart once.
   PLACEHOLDER: the solution -> layer mapping is still ours, not the deck's. */
const SOLUTIONS = LAYERS.flatMap((layer) =>
  SERVICES.filter((s) => s.layer === layer.key).map((s) => ({
    title: s.deckName,
    detail: s.summary,
    layer: layer.key,
  }))
);

export default function Stack() {
  const [active, setActive] = useState<LayerKey>("brand");
  const detailRef = useRef<HTMLDivElement>(null);
  const pinRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    // Width guard BEFORE any plugin registration or trigger creation: no pin
    // is ever created on a narrow or reduced-motion visit, and it is never
    // torn down after the fact -- it is simply never built.
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    if (!window.matchMedia("(min-width: 1024px)").matches) return;
    if (!detailRef.current || !pinRef.current) return;

    gsap.registerPlugin(ScrollTrigger);

    const ctx = gsap.context(() => {
      ScrollTrigger.matchMedia({
        "(min-width: 1024px)": () => {
          ScrollTrigger.create({
            trigger: detailRef.current!,
            start: "top top+=96",
            end: "bottom bottom-=96",
            pin: pinRef.current!,
            pinSpacing: false,
          });

          gsap.utils.toArray<HTMLElement>("[data-solution]").forEach((el) => {
            ScrollTrigger.create({
              trigger: el,
              start: "top center",
              end: "bottom center",
              onToggle: (self) => {
                if (self.isActive) setActive(el.dataset.solution as LayerKey);
              },
            });
          });
        },
      });
    });

    return () => ctx.revert();
  }, []);

  return (
    <section id="stack" className="ground-grain bleed">
      <div
        className="container grid12 section min-w-0"
        style={{ paddingBlock: "clamp(7.5rem,12vw,11rem)" }}
      >
        <div
          ref={pinRef}
          id="stack-pin"
          data-ecosystem-pin
          className="min-w-0"
          style={{ gridColumn: "1 / span 5" }}
        >
          <h2 style={{ fontSize: "clamp(2rem, 4vw, var(--step-2))", maxWidth: "14ch" }}>
            Every layer feeds the next.
          </h2>
          <p
            style={{
              marginTop: "1.25rem",
              color: "var(--color-text-muted)",
              fontSize: "var(--step-0)",
              maxWidth: "34ch",
            }}
          >
            No scattered tools. Brand on the front end, custom systems on the
            back end, AI in the middle, growth on top.
          </p>

          <ol
            id="layers"
            data-layer-active={active}
            style={{ listStyle: "none", margin: "2.5rem 0 0", padding: 0 }}
          >
            {LAYERS.map((layer, i) => (
              <li
                key={layer.key}
                data-layer={layer.key}
                className={`layer${active === layer.key ? " is-active" : ""}`}
                style={{
                  borderTop: "1px solid var(--color-hairline)",
                  borderBottom:
                    i === LAYERS.length - 1 ? "1px solid var(--color-hairline)" : undefined,
                  padding: "1.1rem 0",
                  transition: "none",
                }}
              >
                <span
                  className={`layer-name ${active === layer.key ? "text-accent" : "text-text-muted"}`}
                  style={{
                    fontWeight: 700,
                    fontSize: "var(--step-1)",
                    letterSpacing: "-0.02em",
                    transition: "none",
                  }}
                >
                  {layer.name}
                </span>
                <span
                  style={{
                    display: "block",
                    fontSize: "var(--step--1)",
                    color: "var(--color-text-muted)",
                    marginTop: "0.25rem",
                  }}
                >
                  {layer.gloss}
                </span>
              </li>
            ))}
          </ol>
        </div>

        {/* column 6 deliberately empty */}

        <div ref={detailRef} id="stack-detail" className="min-w-0" style={{ gridColumn: "7 / span 6" }}>
          {SOLUTIONS.map((solution, i) => (
            <article
              key={solution.title}
              data-solution={solution.layer}
              style={{
                paddingBlock: "clamp(3rem,7vw,6rem)",
                borderBottom:
                  i === SOLUTIONS.length - 1 ? undefined : "1px solid var(--color-hairline)",
              }}
            >
              <h3 style={{ fontSize: "clamp(1.75rem, 3.4vw, var(--step-3))", lineHeight: 0.98 }}>
                {solution.title}
              </h3>
              <p
                style={{
                  marginTop: "1rem",
                  color: "var(--color-text-muted)",
                  fontSize: "var(--step-1)",
                  lineHeight: 1.4,
                }}
              >
                {solution.detail}
              </p>
            </article>
          ))}
        </div>
      </div>
    </section>
  );
}
